from pathlib import Path
BASE=Path(__file__).resolve().parent
src=(BASE/'pal.py').read_text(encoding='utf-8').split('\n')
# import only helper defs (lines up to def minde)
exec('\n'.join(src[:36]))
d=json.loads((Path(sys.argv[1]) if len(sys.argv)>1 else BASE/'palette-v7.json').read_text(encoding='utf-8'));P=d['new_primary'];S=d['new_secondary']
V=[views(hex2rgb(c)) for c in P];W=[views(hex2rgb(c)) for c in S]
M=[[0 if i==j else round(float(np.hypot(dpair(V[i],V[j]),.6*dpair(W[i],W[j]))),1) for j in range(16)] for i in range(16)]
o="""// Two-tone 16-civ palette (icon-study). Generated by palette/mkmod.py from palette-v7.json (toned down).
// PAIR_DE[i][j]: min CIEDE2000 (normal/deutan/protan, badge-darkened) combined primary+secondary.
export const CIV_PALETTE_16=%s;
export const PAIR_DE=%s;
const h2=h=>{const n=parseInt(String(h).slice(1,7),16);return [n>>16&255,n>>8&255,n&255];};
// Fallback for saves without secondaryColor: pale, slightly warm tint of the primary.
export function deriveSecondary(color){if(!/^#[0-9a-f]{6}$/i.test(String(color)))return '#d8c8a0';const c=h2(color),t=[232,220,190];return '#'+c.map((v,i)=>Math.round(v*.45+t[i]*.55).toString(16).padStart(2,'0')).join('');}
// Neighbour-aware: greedy permutation so the closest start pairs get the most distinct palette entries.
// dist(i,j) = map distance between player i and j starts. Deterministic (no RNG use).
export function assignCivPalette(n,dist){
  const N=Math.min(n,16),pairs=[];for(let i=0;i<N;i++)for(let j=i+1;j<N;j++)pairs.push([dist(i,j),i,j]);
  const crowd=Array.from({length:N},(_,i)=>pairs.filter(p=>p[1]===i||p[2]===i).reduce((sum,p)=>sum+1/(1+p[0]),0));
  const order=Array.from({length:N},(_,i)=>i).sort((a,b)=>crowd[b]-crowd[a]||a-b);
  const pick=Array(N).fill(-1),used=new Set();
  for(const i of order){let best=-1,bs=-Infinity;for(let k=0;k<16;k++){if(used.has(k))continue;let s=Infinity;for(let j=0;j<N;j++)if(pick[j]>=0){const w=PAIR_DE[k][pick[j]]*Math.sqrt(Math.max(1,dist(i,j)));s=Math.min(s,w);}if(s===Infinity)s=-k;if(s>bs){bs=s;best=k;}}pick[i]=best;used.add(best);}
  return pick.map(k=>CIV_PALETTE_16[k]);
}
"""%(json.dumps([{'color':p,'secondaryColor':s} for p,s in zip(P,S)]),json.dumps(M))
(Path(sys.argv[2]) if len(sys.argv)>2 else BASE.parents[1]/'src/civ-colours.mjs').write_text(o,encoding='utf-8')
